<#
    Builds dist\Invoke-FeatureValidator.ps1: one self-contained file with the engine and the
    whole check catalog inlined. The repo layout stays the source of truth; never edit dist\
    by hand. Rebuild after any change to lib\, checks\ or Invoke-FeatureValidator.ps1.

    Run:  pwsh -File ./build/Build-Standalone.ps1
    Then: pwsh -File ./Tests/Test-FeatureValidator.ps1   (runs every scenario against both)
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent

$main   = Get-Content -Raw -LiteralPath (Join-Path $root 'Invoke-FeatureValidator.ps1')
$engine = Get-Content -Raw -LiteralPath (Join-Path (Join-Path $root 'lib') 'Engine.ps1')

# Catalog: each psd1 must first load through Import-PowerShellDataFile, which only accepts
# data (no commands, no variables). That guarantees the text we inline is pure data even
# though the single file evaluates it as an ordinary expression.
$parts = @()
foreach ($f in (Get-ChildItem -Path (Join-Path $root 'checks') -Filter '*.psd1' | Sort-Object Name)) {
    Import-PowerShellDataFile -Path $f.FullName | Out-Null
    $text = (Get-Content -Raw -LiteralPath $f.FullName).Trim()
    $parts += "    @{ Name = '$($f.Name)'; Data = (`n$text`n    ) }"
}
$catalog = "`$script:EmbeddedCatalog = @(`n" + ($parts -join ",`n") + "`n)"

$pattern = '(?s)#region ENGINE.*?#endregion ENGINE'
if ($main -notmatch $pattern) { throw "ENGINE region marker not found in Invoke-FeatureValidator.ps1" }

$commit = ''
try { $commit = (git -C $root rev-parse --short HEAD 2>$null) } catch { $commit = '' }
$banner = @"
#region ENGINE  (generated by build/Build-Standalone.ps1 from lib/Engine.ps1 and checks/*.psd1 - DO NOT EDIT)
# Source: https://github.com/Mauvlans/AVD/tree/main/feature-validator  $(if ($commit) { "(built from $commit)" })

"@
$inline = $banner + $engine.Trim() + "`n`n# ---------------------------------------------------------------- embedded catalog ----`n" + $catalog + "`n#endregion ENGINE"

# Use a MatchEvaluator so '$' in the engine text is not treated as a regex substitution.
$out = [regex]::Replace($main, $pattern, [System.Text.RegularExpressions.MatchEvaluator] { $inline })

# Sanity: the result must parse, and must not reference files that do not exist in a single file.
$tokens = $null; $errs = $null
[System.Management.Automation.Language.Parser]::ParseInput($out, [ref]$tokens, [ref]$errs) | Out-Null
if ($errs.Count) { throw "Built file does not parse: $($errs[0].Message) (line $($errs[0].Extent.StartLineNumber))" }
if ($out -match 'Join-Path \$PSScriptRoot ''lib''') { throw "Built file still dot-sources lib\Engine.ps1" }

$distDir = Join-Path $root 'dist'
New-Item -ItemType Directory -Path $distDir -Force | Out-Null
$dest = Join-Path $distDir 'Invoke-FeatureValidator.ps1'
# UTF-8 with BOM so Windows PowerShell 5.1 reads non-ASCII text correctly.
[IO.File]::WriteAllText($dest, $out, (New-Object System.Text.UTF8Encoding($true)))
Write-Host "Built $dest ($([math]::Round((Get-Item $dest).Length / 1KB, 1)) KB)" -ForegroundColor Green
